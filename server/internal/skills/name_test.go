package skills_test

import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/kubek80/process-manager/server/internal/skills"
)

// Skills stored by the version that called the portal Process Manager carry that name in their
// last line, which was not part of what decided a new version. The next start (SyncAll) gives
// every one of them a new version in the new words, once, without anybody saving anything; an
// export still recognises the files it wrote under the earlier name as its own.
func TestSkillsOfTheEarlierNameGetTheNewWords(t *testing.T) {
	d, _ := sampleContext(t)
	s := &skills.Store{Pool: d.Pool}
	if err := s.SyncAll(ctx, d); err != nil {
		t.Fatal(err)
	}
	// as the earlier version stored them: its footer, and the hash of the body alone
	rows, err := d.Pool.Query(ctx, `select skill_id, version, content from skill_versions`)
	if err != nil {
		t.Fatal(err)
	}
	type row struct {
		id      string
		version int
		content string
	}
	var all []row
	for rows.Next() {
		var r row
		if err := rows.Scan(&r.id, &r.version, &r.content); err != nil {
			t.Fatal(err)
		}
		all = append(all, r)
	}
	rows.Close()
	for _, r := range all {
		body := r.content[:strings.LastIndex(r.content, "\n---\n\n")]
		sum := sha256.Sum256([]byte(body))
		old := strings.ReplaceAll(r.content, "Pattern Catalog", "Process Manager")
		if _, err := d.Pool.Exec(ctx, `update skill_versions set content = $3, content_hash = $4 where skill_id = $1 and version = $2`, r.id, r.version, old, hex.EncodeToString(sum[:])); err != nil {
			t.Fatal(err)
		}
	}
	if err := s.SyncAll(ctx, d); err != nil {
		t.Fatal(err)
	}
	list, _ := s.List(ctx)
	for _, sk := range list {
		content, _ := s.Content(ctx, sk.ID, 0)
		if sk.Version != 2 || strings.Contains(content, "Process Manager") || !strings.Contains(content, "Generated by Pattern Catalog from the") {
			t.Errorf("%s: version %d:\n%s", sk.ID, sk.Version, content[max(0, len(content)-200):])
		}
	}
	// once: a further start changes nothing
	if err := s.SyncAll(ctx, d); err != nil {
		t.Fatal(err)
	}
	if sk, _ := s.Get(ctx, "process-request-gcp-project"); sk.Version != 2 {
		t.Fatalf("version %d after a second start", sk.Version)
	}
	// an exported file of a withdrawn skill, written under the earlier name, is still removed
	dir := t.TempDir()
	if _, err := d.Pool.Exec(ctx, `update skills set active = false where id = 'process-request-gcp-project'`); err != nil {
		t.Fatal(err)
	}
	gone := filepath.Join(dir, ".claude", "skills", "process-request-gcp-project", "SKILL.md")
	if err := os.MkdirAll(filepath.Dir(gone), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(gone, []byte("old\n\n---\n\nGenerated by Process Manager from the process `request-gcp-project`, version 1."), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := s.ExportDir(ctx, dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(gone); !os.IsNotExist(err) {
		t.Fatalf("the file written under the earlier name is still there: %v", err)
	}
}
