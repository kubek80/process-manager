// ErrNotFound is returned when a skill or one of its versions does not exist.
var ErrNotFound = errors.New("skill not found")

// Skill is a registry entry with its latest version.
type Skill struct {
	ID         string    `json:"id"`
	Kind       string    `json:"kind"`
	SourceKind string    `json:"sourceKind"`
	SourceID   string    `json:"sourceId"`
	Title      string    `json:"title"`
	Extra      string    `json:"extra"`
	Active     bool      `json:"active"`
	Version    int       `json:"version"`
	UpdatedAt  time.Time `json:"updatedAt"`
	Path       string    `json:"path"` // where the file belongs in a repository
}

// VersionInfo describes one generated version.
type VersionInfo struct {
	Version       int       `json:"version"`
	SourceVersion int       `json:"sourceVersion"`
	CreatedAt     time.Time `json:"createdAt"`
}

type Store struct{ Pool *pgxpool.Pool }

// Path is where a generated file belongs in a repository that uses Claude Code.
func Path(kind, id string) string {
	if kind == KindReview {
		return ".claude/agents/" + id + ".md"
	}
	return ".claude/skills/" + id + "/SKILL.md"
}

func hash(s string) string {
	sum := sha256.Sum256([]byte(s))
	return hex.EncodeToString(sum[:])
}

// NewContext collects what the generators need from the current content.
func NewContext(ctx context.Context, d *docs.Store) (Context, error) {
	c, _, err := load(ctx, d)
	return c, err
}

// load reads the lists and every process and standard once.
func load(ctx context.Context, d *docs.Store) (Context, []docs.Doc, error) {
	c := Context{Titles: map[string]string{}, Inactive: map[string]bool{}, Drafts: map[string]bool{}}
	var all []docs.Doc
	var err error
	if c.Lists, err = d.Lists(ctx); err != nil {
		return c, nil, err
	}
	for _, kind := range []string{docs.Process, docs.Standard} {
		list, err := d.List(ctx, kind)
		if err != nil {
			return c, nil, err
		}
		for _, doc := range list {
			if t, ok := docs.TargetOf(doc); ok {
				c.Titles[kind+"/"+doc.ID] = t.Title
				c.Inactive[kind+"/"+doc.ID] = t.Status != "" && t.Status != "active"
				c.Drafts[kind+"/"+doc.ID] = t.Status == "draft"
			}
		}
		all = append(all, list...)
	}
	return c, all, nil
}

// FooterMark starts the last line of every generated file. Export uses it to recognise the
// files it wrote, so that it never removes one written by hand.
const FooterMark = "Generated by Pattern Catalog from the "

// earlierFooterMarks are the footers files written by earlier versions carry (the portal was
// called Process Manager): export still recognises those files as its own.
var earlierFooterMarks = []string{"Generated by Process Manager from the "}

// footer is the last line of a generated file (after FooterMark): the kind, the id, the version
// of the source and of the text. It is part of what decides whether a skill has a new version, so
// that a change of its words (such as the portal's name) reaches every stored skill at the next
// start or `-migrate`, without anybody saving anything.
const footer = "%s `%s`, version %d. This is version %d of the generated text. Do not edit: changes are made in Pattern Catalog.\n"

// generatedHere says whether a file on disk was written by an export of this portal.
func generatedHere(text string) bool {
	if strings.Contains(text, FooterMark) {
		return true
	}
	for _, m := range earlierFooterMarks {
		if strings.Contains(text, m) {
			return true
		}
	}
	return false
}

// SyncSource brings the skills of one process or standard in line with its content as it is
// stored right now (nothing is generated when it no longer exists). A new version is stored
// only when the text changed. Calls for the same source run one after the other and each reads
// the document itself, so the last one to run always works from the latest version.
func (s *Store) SyncSource(ctx context.Context, kind, id string, c Context) error {
	return pgx.BeginFunc(ctx, s.Pool, func(tx pgx.Tx) error {
		if _, err := tx.Exec(ctx, `select pg_advisory_xact_lock(hashtextextended($1, 7462))`, kind+"/"+id); err != nil {
			return err
		}
		extra := map[string]string{}
		rows, err := tx.Query(ctx, `select id, extra from skills where source_kind = $1 and source_id = $2`, kind, id)
		if err != nil {
			return err
		}
		for rows.Next() {
			var sid, e string
			if err := rows.Scan(&sid, &e); err != nil {
				rows.Close()
				return err
			}
			extra[sid] = e
		}
		rows.Close()
		if err := rows.Err(); err != nil {
			return err
		}

		var generated []Generated
		var sourceVersion int
		var body []byte
		err = tx.QueryRow(ctx, `select version, body from documents where kind = $1 and id = $2`, kind, id).Scan(&sourceVersion, &body)
		switch {
		case errors.Is(err, pgx.ErrNoRows): // deleted: everything it produced is withdrawn below
			err = nil
		case err != nil:
			return err
		case kind == docs.Process:
			generated, err = ForProcess(body, c, extra)
		default:
			generated, err = ForStandard(body, c, extra)
		}
		if err != nil {
			return fmt.Errorf("generate skills for %s %s: %w", kind, id, err)
		}

		keep := []string{}
		for _, g := range generated {
			keep = append(keep, g.ID)
			if _, err := tx.Exec(ctx, `insert into skills (id, kind, source_kind, source_id, title) values ($1, $2, $3, $4, $5)
				on conflict (id) do update set title = excluded.title, active = true`, g.ID, g.Kind, kind, id, g.Title); err != nil {
				return err
			}
			var version int
			var latest string
			err := tx.QueryRow(ctx, `select v.version, v.content_hash from skill_versions v where v.skill_id = $1 order by v.version desc limit 1`, g.ID).Scan(&version, &latest)
			if err != nil && !errors.Is(err, pgx.ErrNoRows) {
				return err
			}
			h := hash(g.Body + "\n" + FooterMark + footer)
			if h == latest {
				continue
			}
			version++
			content := g.Body + "\n---\n\n" + FooterMark + fmt.Sprintf(footer, kind, id, sourceVersion, version)
			if _, err := tx.Exec(ctx, `insert into skill_versions (skill_id, version, content, content_hash, source_version) values ($1, $2, $3, $4, $5)`, g.ID, version, content, h, sourceVersion); err != nil {
				return err
			}
			if _, err := tx.Exec(ctx, `update skills set version = $2, updated_at = now() where id = $1`, g.ID, version); err != nil {
				return err
			}
		}
		// whatever this source no longer produces (draft, retired, deleted) is withdrawn, not erased
		_, err = tx.Exec(ctx, `update skills set active = false where source_kind = $1 and source_id = $2 and not (id = any($3))`, kind, id, keep)
		return err
	})
}

// SyncChanged brings the skills in line after one process or standard was saved or deleted:
// its own, and those of every document that names it (its title and whether it has a skill
// appear in their text).
func (s *Store) SyncChanged(ctx context.Context, d *docs.Store, kind, id string) error {
	return s.oneAtATime(ctx, func() error {
		c, all, err := load(ctx, d)
		if err != nil {
			return err
		}
		if err := s.SyncSource(ctx, kind, id, c); err != nil {
			return err
		}
		for _, doc := range all {
			if doc.Kind == kind && doc.ID == id {
				continue
			}
			if docs.UsesOf(doc.Kind, doc.Body).Docs[kind+"/"+id] {
				if err := s.SyncSource(ctx, doc.Kind, doc.ID, c); err != nil {
					return err
				}
			}
		}
		return nil
	})
}

// oneAtATime runs a regeneration alone. Titles and names are read first and written into
// several skills afterwards; two regenerations side by side could otherwise let the one that
// read earlier overwrite what the other wrote from newer content.
func (s *Store) oneAtATime(ctx context.Context, fn func() error) error {
	return db.WithLock(ctx, s.Pool, db.LockSkills, fn)
}

// SyncAll regenerates everything: after an import, and when the lists change (names appear in
// the generated text).
func (s *Store) SyncAll(ctx context.Context, d *docs.Store) error {
	return s.oneAtATime(ctx, func() error { return s.syncAll(ctx, d) })
}

func (s *Store) syncAll(ctx context.Context, d *docs.Store) error {
	c, docsNow, err := load(ctx, d)
	if err != nil {
		return err
	}
	seen := map[string]bool{}
	for _, doc := range docsNow {
		seen[doc.Kind+"/"+doc.ID] = true
		if err := s.SyncSource(ctx, doc.Kind, doc.ID, c); err != nil {
			return err
		}
	}
	all, err := s.List(ctx)
	if err != nil {
		return err
	}
	for _, sk := range all {
		if sk.Active && !seen[sk.SourceKind+"/"+sk.SourceID] {
			if err := s.SyncSource(ctx, sk.SourceKind, sk.SourceID, c); err != nil {
				return err
			}
		}
	}
	return nil
}

const skillColumns = `id, kind, source_kind, source_id, title, extra, active, version, updated_at`

func scanSkill(row pgx.Row) (Skill, error) {
	var sk Skill
	err := row.Scan(&sk.ID, &sk.Kind, &sk.SourceKind, &sk.SourceID, &sk.Title, &sk.Extra, &sk.Active, &sk.Version, &sk.UpdatedAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return sk, ErrNotFound
	}
	sk.Path = Path(sk.Kind, sk.ID)
	return sk, err
}

// List returns every skill, active ones first, then by id.
func (s *Store) List(ctx context.Context) ([]Skill, error) {
	rows, err := s.Pool.Query(ctx, `select `+skillColumns+` from skills order by active desc, id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Skill{}
	for rows.Next() {
		sk, err := scanSkill(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, sk)
	}
	return out, rows.Err()
}

// ActiveCount returns how many skills and review agents are in use.
func (s *Store) ActiveCount(ctx context.Context) (int, error) {
	var n int
	err := s.Pool.QueryRow(ctx, `select count(*) from skills where active`).Scan(&n)
	return n, err
}

// Get returns one skill.
func (s *Store) Get(ctx context.Context, id string) (Skill, error) {
	return scanSkill(s.Pool.QueryRow(ctx, `select `+skillColumns+` from skills where id = $1`, id))
}

// Content returns the text of a version; version 0 means the latest.
func (s *Store) Content(ctx context.Context, id string, version int) (string, error) {
	var content string
	err := s.Pool.QueryRow(ctx, `select content from skill_versions where skill_id = $1 and (version = $2 or $2 = 0) order by version desc limit 1`, id, version).Scan(&content)
	if errors.Is(err, pgx.ErrNoRows) {
		return "", ErrNotFound
	}
	return content, err
}

// Versions lists the versions of a skill, newest first.
func (s *Store) Versions(ctx context.Context, id string) ([]VersionInfo, error) {
	rows, err := s.Pool.Query(ctx, `select version, source_version, created_at from skill_versions where skill_id = $1 order by version desc`, id)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []VersionInfo{}
	for rows.Next() {
		var v VersionInfo
		if err := rows.Scan(&v.Version, &v.SourceVersion, &v.CreatedAt); err != nil {
			return nil, err
		}
		out = append(out, v)
	}
	return out, rows.Err()
}

// SetExtra stores the hand-written guidance of a skill. The caller regenerates afterwards.
func (s *Store) SetExtra(ctx context.Context, id, extra string) error {
	tag, err := s.Pool.Exec(ctx, `update skills set extra = $2 where id = $1`, id, extra)
	if err == nil && tag.RowsAffected() == 0 {
		return ErrNotFound
	}
	return err
}

// ExportDir writes the latest version of every active skill into dir, laid out the way a
// repository that uses Claude Code expects. Files of skills that were withdrawn are removed,
// but only when they carry the footer of a generated file. Each written skill is passed to
// written, if given (an export counts as a download of every skill it writes).
func (s *Store) ExportDir(ctx context.Context, dir string, written ...func(Skill)) (int, error) {
	list, err := s.List(ctx)
	if err != nil {
		return 0, err
	}
	n := 0
	for _, sk := range list {
		path := filepath.Join(dir, filepath.FromSlash(sk.Path))
		if !sk.Active {
			if old, err := os.ReadFile(path); err == nil && generatedHere(string(old)) {
				if err := os.Remove(path); err != nil {
					return n, err
				}
				if sk.Kind != KindReview {
					_ = os.Remove(filepath.Dir(path)) // the skill's own folder, if it is empty now
				}
			}
			continue
		}
		content, err := s.Content(ctx, sk.ID, 0)
		if err != nil {
			return n, err
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return n, err
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return n, err
		}
		for _, fn := range written {
			fn(sk)
		}
		n++
	}
	return n, nil
}
