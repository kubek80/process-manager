/**
 * Writes src/lib/validators.generated.js: the checks for the three formats, generated from
 * schema/*.schema.json. Run `npm run validators` after changing a schema.
 *
 * Why ahead of time: building the checks in the browser needs `eval`, which the app's content
 * security policy forbids - a page that cannot run generated code cannot be tricked into
 * running somebody else's.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020";
import standaloneCode from "ajv/dist/standalone";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const target = path.join(root, "src", "lib", "validators.generated.js");

const header = `// Generated by \`npm run validators\` from schema/*.schema.json. Do not edit: change the schema and run it again.
/* eslint-disable */
// The two helpers the generated code needs, so that it depends on nothing at run time.
function ucs2length(str) {
  let length = 0, pos = 0;
  while (pos < str.length) {
    length++;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < str.length && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos++;
  }
  return length;
}
function equal(a, b) {
  if (a === b) return true;
  if (!a || !b || typeof a !== "object" || typeof b !== "object") return a !== a && b !== b;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  if (Array.isArray(a)) return a.length === b.length && a.every((x, i) => equal(x, b[i]));
  const keys = Object.keys(a);
  return keys.length === Object.keys(b).length && keys.every((k) => Object.prototype.hasOwnProperty.call(b, k) && equal(a[k], b[k]));
}
`;

/** The text of the generated file for the schemas as they are now. */
export function generate(): string {
  const read = (name: string) => JSON.parse(fs.readFileSync(path.join(root, "schema", name), "utf8"));
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
  ajv.addSchema(read("process.schema.json"), "process");
  ajv.addSchema(read("standard.schema.json"), "standard");
  ajv.addSchema(read("catalog.schema.json"), "catalog");
  let code = standaloneCode(ajv, { validateProcessDoc: "process", validateStandardDoc: "standard", validateCatalogDoc: "catalog" });
  code = code.replace(/^"use strict";/, "")
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length")
    .replaceAll('require("ajv/dist/runtime/equal").default', "equal");
  if (/\brequire\(|new Function|\beval\(/.test(code)) throw new Error("the generated checks need something that is not available in the browser");
  return header + code + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(target, generate());
  console.log(`Wrote ${path.relative(root, target)}`);
}
