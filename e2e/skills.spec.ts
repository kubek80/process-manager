import fs from "node:fs";
import { expect, test } from "@playwright/test";
import { ALEX, DANA, fields, open, publish, readSkill, SAM, saveDraft, signIn } from "./helpers";

const APIGEE = "onboard-api-to-apigee";

test("everyone can read and download the skill of a process", async ({ page }) => {
  await signIn(page, SAM);
  await open(page, "/p/request-gcp-project/skills");
  await expect(page.locator(".skill-head h3")).toHaveText("Process: Request a GCP project");
  // what it is for in one sentence; where the file goes behind "Where to put it"
  await expect(page.locator(".skill-purpose")).toHaveText("Lets an AI coding assistant walk a person through this process: it does their steps and says who does the others.");
  const where = page.locator("details.skill-where");
  await expect(where.locator("code")).toBeHidden();
  await where.getByText("Where to put it").click();
  await expect(where.locator("code")).toHaveText(".claude/skills/process-request-gcp-project/SKILL.md");
  // the preview leaves out the front matter, which only the assistant reads; the download keeps it
  const content = page.getByLabel("What the skill says");
  await expect(content).toHaveClass(/\bskill-content\b/);
  await expect(content).not.toContainText("name: process-request-gcp-project");
  await expect(content).toContainText("Never perform a step of another participant, and never approve anything.");
  await expect(content).toContainText("1. **You** - Decide the project details");
  await expect(content).toContainText("Infrastructure as code (skill `standard-infrastructure-as-code`)");
  await expect(page.getByRole("button", { name: /Add guidance/ })).toHaveCount(0); // not for a consumer

  const [download] = await Promise.all([page.waitForEvent("download"), page.getByRole("link", { name: "Download" }).click()]);
  expect(download.suggestedFilename()).toBe("SKILL.md");
  const text = fs.readFileSync(await download.path(), "utf8");
  expect(text.startsWith("---\nname: process-request-gcp-project\n")).toBe(true);
  expect(text).toContain("Generated by Pattern Catalog from the process `request-gcp-project`, version ");
});

test("publishing a process gives its skill a new version; a saved draft does not", async ({ page }) => {
  await signIn(page, ALEX);
  const before = await readSkill(page, `process-${APIGEE}`);
  await open(page, `/p/${APIGEE}/edit`);
  await page.locator(".edit-preview .block", { hasText: "Announce the API to consumers" }).click();
  const drawer = fields(page);
  await drawer.getByRole("button", { name: "Add action" }).click();
  await drawer.getByPlaceholder("Describe one action").last().fill("Add the API to the service catalogue.");
  await saveDraft(page);
  // unpublished changes do not reach the skill
  const drafted = await readSkill(page, `process-${APIGEE}`);
  expect(drafted.skill.version).toBe(before.skill.version);
  expect(drafted.content).not.toContain("Add the API to the service catalogue.");
  await publish(page);
  await page.locator(".edit-bar").getByRole("button", { name: "Back to reading" }).click();

  await page.getByRole("tab", { name: "Skills" }).click();
  await expect(page.locator(".skill-content")).toContainText("Add the API to the service catalogue.");
  await expect(page.locator(".skill-content")).toContainText(`This is version ${before.skill.version + 1} of the generated text.`);
  const after = await readSkill(page, `process-${APIGEE}`);
  expect(after.skill.version).toBe(before.skill.version + 1);
  expect(after.versions).toHaveLength(before.versions.length + 1);
});

test("the registry lists every skill and review agent; extra guidance survives regeneration", async ({ page }) => {
  await signIn(page, DANA);
  await open(page, "/admin/skills");
  const items = page.locator(".cat-item");
  await expect(items.filter({ hasText: "Process: Request a GCP project" })).toBeVisible();
  const kinds = page.getByRole("group", { name: "Kind" });
  await expect(kinds.locator("button.seg-item")).toHaveCount(3);
  await expect(kinds.getByRole("button", { name: /^All/ })).toHaveAttribute("aria-pressed", "true");
  const agents = kinds.getByRole("button", { name: /^Review agents/ });
  await agents.click();
  await expect(agents).toHaveAttribute("aria-pressed", "true");
  await expect(agents).toHaveClass(/\bon\b/);
  await expect(items.filter({ hasText: "Review: Infrastructure as code" })).toBeVisible();
  await expect(items.filter({ hasText: "Process:" })).toHaveCount(0);
  await page.getByPlaceholder("Search skills").fill("infrastructure");
  await expect(items).toHaveCount(1);
  await items.first().click();

  const panel = page.locator(".skill-panel");
  await expect(panel.locator(".skill-purpose")).toHaveText("Lets an AI assistant check a pull request against this standard and point out what does not meet it.");
  await panel.locator("details.skill-where summary").click();
  await expect(panel.locator("details.skill-where code")).toHaveText(".claude/agents/review-infrastructure-as-code.md");
  await expect(panel.getByLabel("What the review agent says")).toBeVisible();
  await expect(panel.locator(".skill-content")).toContainText("### IAC-03 · Pin versions · MUST · report as blocker");
  await expect(panel.locator(".skill-content")).toContainText("## Not checked in this review");
  const before = (await readSkill(page, "review-infrastructure-as-code")).skill.version;

  await panel.getByRole("button", { name: "Add guidance" }).click();
  await panel.locator(".skill-extra textarea").fill("Modules under examples/ are exempt from IAC-04.");
  await panel.getByRole("button", { name: "Save and regenerate" }).click();
  await expect(panel.locator(".skill-content")).toContainText("## Additional guidance");
  await expect(panel.locator(".skill-content")).toContainText("Modules under examples/ are exempt from IAC-04.");
  await expect(items.first().locator(".cat-uses")).toHaveText(`v${before + 1}`);

  // the version before is still there, without the guidance
  await panel.locator(".skill-version select").selectOption(String(before));
  await expect(panel.locator(".skill-content")).not.toContainText("Additional guidance");

  await panel.locator("..").getByRole("link", { name: /Open the standard it comes from/ }).click();
  await expect(page.getByRole("heading", { name: "Infrastructure as code", exact: true })).toBeVisible();
});
